// Generic SAE J2012 ranges, for codes no list knows: what part of the car they concern.
function dtcRange(c) {
  var k = c.charAt(0), d1 = c.charAt(1), d2 = c.charAt(2);
  var maker = d1 === '1' || d1 === '3';
  if (k === 'P') {
    var g = { '0': 'yakıt / hava ölçümü, emisyon', '1': 'yakıt / hava ölçümü', '2': 'yakıt / hava ölçümü (enjektör)', '3': 'ateşleme / tekleme',
      '4': 'ek emisyon (EGR, DPF, katalizör)', '5': 'hız / rölanti kontrolü', '6': 'motor beyni ve çıkışları', '7': 'şanzıman', '8': 'şanzıman', '9': 'şanzıman',
      'A': 'hibrit / elektrikli', 'B': 'hibrit / elektrikli', 'C': 'hibrit / elektrikli' }[d2] || 'motor / şanzıman';
    return (maker ? 'Üreticiye özel · ' : '') + 'Motor · ' + g;
  }
  if (k === 'C') return (maker ? 'Üreticiye özel · ' : '') + 'Şasi (fren, direksiyon, süspansiyon)';
  if (k === 'B') return (maker ? 'Üreticiye özel · ' : '') + 'Gövde (klima, kapı, aydınlatma, airbag)';
  return (maker ? 'Üreticiye özel · ' : '') + 'Modüller arası haberleşme';
}
